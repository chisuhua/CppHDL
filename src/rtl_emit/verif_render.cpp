// src/rtl_emit/verif_render.cpp
//
// **Verilog 渲染器** —— 执行后端之二（`rtl-verification-single-source` · ADR-074 D1）。
//
// ⚠️ 端口连线 / 时钟 / 复位 / 收尾来自 `write_tb_prelude` / `write_tb_reset_pulse` /
//    `write_tb_epilogue`（**与骨架共用** ⇒ ⇒ 无手写映射表）。
// ⚠️ 时序锚点：驱动在「沿后采样窗」内；观测在「最近一次结算之后」⇒ ⇒ 统一
//    `@(posedge clk); #1;`（**禁 `#0`**）。
// ⚠️ **fail-closed**：端口不可解析 / 用到 TICK·WAIT 但设计无时钟 ⇒ 返回 false。

#include "rtl_emit/verif.h"

#include "rtl_emit/tb_stub.h"

#include <ostream>
#include <string>
#include <unordered_map>
#include <vector>

namespace ch {
namespace rtl_emit {
namespace {

constexpr const char *kGenerator = "@generated by cpphdl rtl_emit::verif (DO NOT EDIT)";

struct PortInfo {
    std::string name;  // 产物端口名
    std::uint32_t width = 1;
};

struct PortTable {
    std::unordered_map<std::string, PortInfo> by_member;
    std::unordered_map<std::string, PortInfo> by_name;

    bool build(const RtlManifest &manifest) {
        for (const auto &p : manifest.port_table) {
            by_name[p.name] = PortInfo{p.name, p.width};
        }
        for (const auto &e : manifest.ports) {
            if (!e.is_top_io || e.cpp_member.empty()) {
                continue;
            }
            if (e.cpp_member == "unnamed_input" || e.cpp_member == "unnamed_output") {
                continue;
            }
            by_member[e.cpp_member] = PortInfo{e.name, e.width};
        }
        return true;
    }

    bool resolve(const std::string &ident, PortInfo &out) const {
        if (auto it = by_member.find(ident); it != by_member.end()) {
            out = it->second;
            return true;
        }
        if (auto it = by_name.find(ident); it != by_name.end()) {
            out = it->second;
            return true;
        }
        return false;
    }
};

std::string lit(std::uint32_t width, std::uint64_t value) {
    if (width == 0) {
        width = 1;
    }
    const std::uint64_t mask =
        (width >= 64) ? ~static_cast<std::uint64_t>(0)
                      : ((static_cast<std::uint64_t>(1) << width) - 1);
    return std::to_string(width) + "'d" + std::to_string(value & mask);
}

} // namespace

bool render_tb(std::ostream &out, const VerifProgram &program, const RtlManifest &manifest,
               const TbRenderOptions &options, std::string &error) {
    PortTable ports;
    ports.build(manifest);

    TbStubOptions stub_opts;
    stub_opts.dut_module = options.dut_module;
    stub_opts.tb_module = options.tb_module;
    stub_opts.example_hint = options.example_hint;
    stub_opts.clock_half_period_ns = options.clock_half_period_ns;
    stub_opts.reset_cycles = options.reset_cycles;

    // ⚠️ 先解析**全部**端口名 ⇒ 任一失败即 fail-closed（不产出半成品）
    for (const auto &sc : program.scenarios) {
        for (const auto &op : sc.ops) {
            if (op.port.empty()) {
                continue;
            }
            PortInfo info;
            if (!ports.resolve(op.port, info)) {
                error = "场景 `" + sc.name + "` 的端口 `" + op.port +
                        "` 无法解析（未具名 / 拼写错误 / 不在产品端口表）";
                return false;
            }
        }
    }

    const std::string expect_src = options.expect_src.empty() ? program.expect_src
                                                              : options.expect_src;
    std::vector<std::string> header;
    header.push_back(kGenerator);
    if (!expect_src.empty()) {
        // ⚠️ 行首形态 MUST 是 `// EXPECT-SRC:`（护栏 ②' 逐字匹配）
        out << "// EXPECT-SRC: " << expect_src << "\n";
        header.push_back("");
    }
    header.push_back("验证源 = `.verif`（**单一语义来源**）⇒ 本文件由 IR 渲染，MUST NOT 手改。");
    header.push_back("期望值的**推导**在 `EXPECT-SRC` 指向的登记文档；本文件只承载机器值。");

    const auto pre = write_tb_prelude(out, manifest, stub_opts, header);

    // 无时钟却用到需要推进拍的原语 ⇒ fail-closed
    if (pre.clock_port.empty()) {
        for (const auto &sc : program.scenarios) {
            for (const auto &op : sc.ops) {
                if (op.kind == VerifOpKind::Tick || op.kind == VerifOpKind::Wait ||
                    op.kind == VerifOpKind::ExpectStable || op.kind == VerifOpKind::Reset) {
                    error = "设计无 `role == clock` 端口，但验证源用到需要推进时钟的原语";
                    return false;
                }
            }
        }
    }
    const std::string clk = pre.clock_port;

    out << "    initial begin\n";
    write_tb_reset_pulse(out, stub_opts, pre);

    for (const auto &sc : program.scenarios) {
        out << "        // ── scenario: " << sc.name;
        if (!sc.anchor.empty()) {
            out << "  (anchor: " << sc.anchor << ")";
        }
        out << " ──\n";
        for (const auto &op : sc.ops) {
            PortInfo info;
            switch (op.kind) {
            case VerifOpKind::Tick:
                out << "        repeat (" << op.count << ") @(posedge " << clk << ");\n";
                out << "        #1;\n";
                break;
            case VerifOpKind::Settle:
                out << "        #1;\n";
                break;
            case VerifOpKind::Set:
                ports.resolve(op.port, info);
                out << "        " << info.name << " = " << lit(info.width, op.value) << ";\n";
                break;
            case VerifOpKind::Reset:
                ports.resolve(op.port, info);
                out << "        " << info.name << " = " << lit(info.width, op.value) << ";\n";
                out << "        repeat (" << op.count << ") @(posedge " << clk << ");\n";
                out << "        " << info.name << " = " << lit(info.width, op.value ? 0 : 1)
                    << ";\n";
                out << "        #1;\n";
                break;
            case VerifOpKind::Wait:
                ports.resolve(op.port, info);
                out << "        wait_ok = 1'b0;\n";
                out << "        for (wi = 0; wi < " << op.count << "; wi = wi + 1) begin\n";
                out << "            @(posedge " << clk << "); #1;\n";
                if (op.level == WaitLevel::Low) {
                    // `low` ≡ 值 == 0 ⇒ 用 `==`（X 时表达式为 X ⇒ `if` 判假 ⇒ **fail-closed**）
                    out << "            if (" << info.name << " == 0) begin\n";
                } else {
                    // `high` ≡ 值 != 0（≡ 缺省）⇒ ⚠️ 本行文本 MUST 逐字不变（默认路径零改动）
                    out << "            if (" << info.name << " !== 0) begin\n";
                }
                out << "                wait_ok = 1'b1; wi = " << op.count << ";\n";
                out << "            end\n";
                out << "        end\n";
                out << "        checks = checks + 1;\n";
                out << "        if (!wait_ok) begin fails = fails + 1; "
                       "$display(\"CHECK "
                    << op.check_id << " FAIL (timeout " << info.name
                    << ")\"); end else $display(\"CHECK " << op.check_id << " PASS\");\n";
                break;
            case VerifOpKind::Expect:
                ports.resolve(op.port, info);
                out << "        checks = checks + 1;\n";
                out << "        if (" << info.name << " !== " << lit(info.width, op.value)
                    << ") begin fails = fails + 1; $display(\"CHECK " << op.check_id
                    << " FAIL (" << info.name << ")\"); end else $display(\"CHECK "
                    << op.check_id << " PASS\");\n";
                break;
            case VerifOpKind::ExpectStable:
                ports.resolve(op.port, info);
                out << "        hold_val = " << info.name << ";\n";
                out << "        for (wi = 0; wi < " << op.count << "; wi = wi + 1) begin\n";
                out << "            @(posedge " << clk << "); #1;\n";
                out << "            checks = checks + 1;\n";
                out << "            if (" << info.name << " !== hold_val["
                    << (info.width - 1) << ":0]) begin fails = fails + 1; $display(\"CHECK "
                    << op.check_id << " FAIL (unstable " << info.name
                    << ")\"); end else $display(\"CHECK " << op.check_id << " PASS\");\n";
                out << "        end\n";
                break;
            case VerifOpKind::Observe:
                ports.resolve(op.port, info);
                out << "        $display(\"OBSERVE " << sc.name << " " << info.name
                    << "=%0d\", " << info.name << ");\n";
                break;
            }
        }
        out << "\n";
    }

    write_tb_epilogue(out, options.tb_module);
    return true;
}

} // namespace rtl_emit
} // namespace ch
